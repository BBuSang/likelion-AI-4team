"""기획안 5-1 결과 보고서 → reports/5-1_수집.md (audit_01.py 다음에 실행)

    python pipeline/report_01.py
"""
import csv
import json
from collections import Counter, defaultdict

from common import REPORTS, WORK

csv.field_size_limit(2**31 - 1)
W = WORK / "01_fetch"


def main():
    a = json.loads((W / "audit.json").read_text(encoding="utf-8"))
    s = json.loads((W / "selected.json").read_text(encoding="utf-8"))
    ac = list(csv.DictReader(open(W / "article_counts.csv", encoding="utf-8-sig")))
    rows = list(csv.DictReader(open(W / "articles_raw.csv", encoding="utf-8-sig")))
    ut = Counter(r["unit_type"] for r in rows)
    L = []
    p = L.append
    ok = lambda k: "✅ 통과" if a[k]["pass"] else "❌ 실패"

    p("# 5-1 데이터 수집 결과\n")
    p(f"기준일 **{s['checked_on'][:4]}-{s['checked_on'][4:6]}-{s['checked_on'][6:]}** · 규칙 `{s['rule']}` · "
      "코드 `pipeline/fetch_01.py`, `pipeline/audit_01.py`, `pipeline/report_01.py`\n")
    p("## 한눈에 보기\n")
    by = Counter(c["scope"] for c in s["chosen"])
    art = defaultdict(int)
    for r in ac:
        art[r["scope"]] += int(r["csv_articles"])
    n_unsplit = len(a["5"]["분리 전 행정규칙 (5-2-3에서 셈)"])
    desc = {"A": "핵심 44개 법률", "B": "A의 시행령·시행규칙", "C": "감독규정 등 행정규칙 (고시·세칙)", "D": "그 밖에 받은 법령"}
    p("| 묶음 | 내용 | 법령 수 | 조문 수 |\n|---|---|---|---|")
    for k in "ABCD":
        extra = f" (+ 한 덩어리로 온 {n_unsplit}개)" if k == "C" else ""
        p(f"| {k} | {desc[k]} | {by[k]} | {art[k]:,}{extra} |")
    p(f"| **합계** | | **{len(s['chosen'])}** | **{sum(art.values()):,}** (삭제 조문 {a['5']['삭제 조문']:,} 포함) |\n")
    drop = Counter(d["why"].split(" (")[0].split(":")[0] for d in s["dropped"])
    p("- 원본(`data/source/api`) 438개 + 예정판 4개를 캐시로 쓰고, **API로 새로 받은 것 21개** (`data/work/01_fetch/api/`)")
    p("  - 원본보다 새 판 6개: 자본시장법·자본시장법 시행령(11/13 시행), 건축법·약사법(11/12), 전세사기피해자법(11/13), 행정절차법 시행령(원본에 없던 B 하위 법령)")
    p("  - 같은 판이지만 시행일자가 늦게 잡힌 것(단계적 시행) 12개 + 행정규칙 2개: 기준일 시행일자로 다시 받음 (아래 '고친 것' 1)")
    p("  - 행정규칙 새 판 1개: 보험업감독규정(11/09)")
    p(f"- 뺀 파일 {len(s['dropped'])}개: " + ", ".join(f"{k} {v}" for k, v in drop.most_common()))
    p("  - 범위 밖 = 훈령·공고 등 행정규칙 54 + 대법원규칙(법원인사사무규칙) 1 (기획안 3-2)")
    p("- 원본 손대지 않음 (원본은 `data/source/`, 새로 받은 것은 `data/work/01_fetch/api/`)\n")

    p("## 판단 기준 점검 (기획안 5-1)\n")
    p("| # | 기준 | 결과 | 내용 |\n|---|---|---|---|")
    n = len(s["chosen"])
    p(f"| 1 | 목록 수 = 받은 수 | {ok('1')} | 최종 목록 {n} = 본문 파일 {a['1']['본문 파일']} = 파싱 성공 {a['1']['파싱 성공']} = CSV 법령 {a['1']['CSV에 있는 법령']} |")
    p(f"| 2 | 핵심 44개 법률 | {ok('2')} | {a['2']['A 법률']} |")
    t = a["3"]["표"]
    p(f"| 3 | 하위 법령 | {ok('3')} | API에 현행이 있는 시행령 {sum(r['시행령'].startswith('있음') for r in t)}개·"
      f"시행규칙 {sum(r['시행규칙'].startswith('있음') for r in t)}개 모두 받음 (표 아래) |")
    p(f"| 4 | 현행판 | {ok('4')} | 예정판 0, {n}개 모두 시행일자 = API 현행 시행일자 |")
    p(f"| 5 | 조문 수 | {ok('5')} | 원본 조문 수 = CSV 조문 행 수, 차이 0 (법령 {a['5']['법령']}개). 조문으로 안 나뉜 행정규칙 {n_unsplit}개는 5-2에서 셈 |")
    s6 = a["6"]["화면 대조"]
    p(f"| 6 | 원문 대조 | {ok('6')} | 국가법령정보센터 화면과 {len(s6)}개 법령 대조: {sum(x['판정'] == '일치' for x in s6)}개 일치, "
      f"{sum(x['판정'].startswith('시행 예정') for x in s6)}개는 시행 전 조문 차이 (아래) |")
    p(f"| 7 | 원본 목록 차이 설명 | {ok('7')} | `index.jsonl` {a['7']['index.jsonl']}건 ↔ 원본 파일 {a['7']['원본 파일']}건: "
      f"목록에 없는 파일 {len(a['7']['목록에 없는 파일'])}개 → 모두 범위 안, 최종 선택됨 |")
    p(f"| 8 | 비밀값 | {ok('8')} | 저장한 파일 {a['8']['검사 파일']}개에서 인증값 0건 |\n")

    p("### 3. 핵심 44개 법률의 하위 법령\n")
    p("`있음/받음` = API에 현행판 있음 / 받음, `없음/-` = API에 그 이름의 현행 법령이 없음 (예: 민법 시행령, 은행법 시행규칙은 존재하지 않음)\n")
    p("| 법률 | 시행령 | 시행규칙 |\n|---|---|---|")
    for r in t:
        p(f"| {r['법률']} | {r['시행령']} | {r['시행규칙']} |")

    p("\n### 5. 법령별 조문 수 (A·B, 전체 표는 `data/work/01_fetch/article_counts.csv`)\n")
    p("삭제 = 조문 머리와 태그를 뗀 본문이 `삭제`뿐인 조문 (가지조문 `제28조의6 삭제` 포함)\n")
    p("| 묶음 | 법령 | 구분 | 원본 조문 | CSV 조문 | 삭제 | 처음 ~ 끝 |\n|---|---|---|---|---|---|---|")
    for r in ac:
        if r["scope"] in "AB":
            p(f"| {r['scope']} | {r['law_name']} | {r['level']} | {r['src_articles']} | {r['csv_articles']} | {r['deleted']} | {r['first']} ~ {r['last']} |")
    p(f"\n조문으로 나뉘지 않고 한 덩어리로 온 행정규칙 {n_unsplit}개 (5-2에서 조문을 나눠 셈):")
    p("- " + ", ".join(a["5"]["분리 전 행정규칙 (5-2-3에서 셈)"]))

    p("\n### 6. 국가법령정보센터 화면 대조\n")
    p("A·B에서 무작위 5개(seed 20261113) + 원본 PDF가 있는 법령 5개. 화면(`lsInfoR.do`)의 본문 조문 번호 목록과 우리 CSV 조문 번호 목록을 하나씩 비교.\n")
    p("| 법령 | 시행일자 | 우리 | 화면 | 화면에만 있는 조문 | 판정 |\n|---|---|---|---|---|---|")
    for x in s6:
        p(f"| {x['법령']} | {x['시행일자']} | {x['우리']} | {x['화면']} | {', '.join(x['화면에만']) or '-'} | {x['판정']} |")
    p("\n- 개인정보 보호법 제28조의12~15(인공지능기술 개발 특례)는 **2027-03-09 시행 예정** 조문이다 (원본 PDF의 `[시행일: 2027. 3. 9.]`로 확인). "
      "화면은 시행 전 조문도 같이 보여 주고, 우리는 현행만 받으므로 빠지는 것이 맞다.")
    p("- PDF 조문 수는 참고만 한다. PDF는 목차 줄과 시행 예정 조문까지 함께 세어져서(외국환거래법 39 vs 화면·우리 37) 기준으로 쓰기 어렵다.\n")

    p("### 7. 원본 목록에 없던 파일\n")
    p("| 법령 | 판(시행일자) | 묶음 | 최종 선택 |\n|---|---|---|---|")
    for x in a["7"]["목록에 없는 파일"]:
        p(f"| {x['법령']} | {x['판']} | {x['범위']} | {'O' if x['최종 선택'] else 'X'} |")
    p("\n→ 지난 작업에서 이름으로 하위 법령을 받거나 새 판을 받을 때 `index.jsonl`을 갱신하지 않은 것. 이번에는 목록 파일을 믿지 않고 **파일을 직접 읽어** 목록을 만들었다.\n")

    p("### 뺀 파일 (범위 밖 행정규칙 54개 제외)\n")
    p("| 법령 | 판 | 묶음 | 이유 |\n|---|---|---|---|")
    for x in a["뺀 파일 목록"]:
        p(f"| {x['법령']} | {x['판']} | {x['범위']} | {x['이유']} |")
    law_out = [d for d in s["dropped"] if d.get("target") == "law" and d["why"].startswith("범위 밖")]
    for d in law_out:
        p(f"| {d['name']} | {d['effective']} | 제외 | {d['why']} |")

    p("\n## 점검하면서 고친 것\n")
    p("1. **같은 판인데 시행일자가 다른 법령 13개 (기준 4 처음 실패)**: 판 번호(MST)는 같지만 API 현행 시행일자가 원본 파일보다 늦었다 "
      "(예: 소득세법 원본 2026-01-01 → 현행 2026-07-01). 한 번 개정된 법이 조문마다 다른 날 시행되는 **단계적 시행** 때문이고, "
      "원본은 앞 날짜 기준이라 늦게 시행된 조문 내용이 빠져 있을 수 있다 → 기준일 시행일자로 다시 받음 (`efYd=현행 시행일자`). 기획안 5-1 수집 규칙에 추가.")
    p("2. **조문 0인 행정규칙 18개 (기준 5 처음 실패)**: 원본에서 조문이 한 덩어리 글로 온 것. 수집 실패가 아니라 5-2 파싱 대상 → "
      "기준 5는 '법령 + 조문으로 나뉘어 온 행정규칙'에 적용하도록 기획안 수정.")
    p("3. **화면 대조 방식 (기준 6 처음 실패)**: 조문 '개수'만 비교하면 시행 예정 조문 때문에 틀린 것처럼 보임 → 조문 **번호 목록**을 비교하고, "
      "화면에만 있는 조문은 시행일이 기준일 뒤인지 확인하도록 바꿈.")
    p("4. **삭제 조문 수 (처음 보고 1,151 → 1,821)**: 처음 규칙(`제N조 삭제`로 시작)이 `제28조의6 삭제` 같은 가지조문 삭제를 놓쳤다. "
      "전처리 기준을 다시 보면서 발견 → 조문 머리를 뗀 본문이 `삭제`뿐인지로 셈 (`audit_01.py is_deleted`).")
    p("5. **법원인사사무규칙(대법원규칙) 제외**: 지난 팀 목록에서 D로 들어온 법원 내부 인사 규칙. 사용자 결정으로 범위에서 뺌 (기획안 3-2). 법령 381 → 380.\n")

    p("## 다음 단계(5-2)로 넘길 것\n")
    p("- 행정규칙 96개 중 **78개는 조문 목록**으로 오고, **18개만 한 덩어리**다. 18개에 금융투자업규정(35만 자)·보험업감독규정·외국환거래규정 같은 핵심 감독규정이 많다. "
      "`신용협동조합인가지침`처럼 `1. 목 적` 형식인 지침도 있다.")
    p("- **행정규칙 조문에는 줄바꿈이 없다** (항·호가 한 줄에 붙어 있음) → 5-2에서 줄바꿈을 넣어야 청크를 경계로 자를 수 있다.")
    p("- 조문으로 온 행정규칙에도 장·절 제목 칸 376개가 섞여 있다.")
    p(f"- 별표가 있는 법령 {sum(c['has_annex'] for c in s['chosen'])}개 (이번 범위에서는 제외, 개수만 기록).\n")

    p("## 결과 파일 (`data/work/01_fetch/`)\n")
    p("| 파일 | 내용 |\n|---|---|")
    p(f"| `laws.csv` | 최종 법령 {n}개: 묶음, 법령명, 구분, 원래 종류, 법령ID, 판 번호(MST), 약칭, 소관부처, 시행일자, 공포일자, 상위 법률, 업권, 회신 사례 수, 조문 수, 출처 파일 |")
    p(f"| `articles_raw.csv` | 조문 단위 원문 {len(rows):,}행 (조문 {ut['조문']:,} + 장·절 제목 {ut['전문']:,} + 행정규칙 기타 칸 {ut['기타(장·절 등)']:,} "
      f"+ 분리 전 덩어리 {ut['본문(분리 전)']:,}). 컬럼: 법령, 구분, 묶음, 조문키, 단위 종류, 조문번호, 조문제목, 원문, 조문 시행일자, 법령 시행일자 |")
    p("| `article_counts.csv` | 법령별 조문 수 대조표 (기준 5) |")
    p("| `selected.json`, `audit.json` | 최종 선택·뺀 파일과 이유, 점검 결과 원자료 |")
    p("| `fetch_log.jsonl`, `cache/` | API 요청 기록(인증값 없음), 응답 캐시 |")
    REPORTS.mkdir(exist_ok=True)
    (REPORTS / "5-1_수집.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("reports/5-1_수집.md", len(L), "줄")


if __name__ == "__main__":
    main()

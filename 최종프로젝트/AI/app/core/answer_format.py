"""답변 공통 형식 — 사내·사내+공개 종합·법령·금융상품·비조치의견서 답변이 모두 같은 틀을 쓴다.

두괄식: 결론(제목 없이 맨 앞) → 상세 설명 → 유의사항(있을 때만). 화면은 마크다운을 그대로 그린다 (AnswerMarkdown).
경로마다 다른 것은 인용 표시([H0071]·[LAW-1]·[1]·[L3577])와 '못 찾음' 문장뿐이라 그 둘만 넘겨받는다.
못 찾았을 때는 제목 없이 그 문장만 — '못 찾음' 판정(rag.chat._NOT_FOUND 등)과 안내 문구 바꾸기가 그 문장에 맞춰 동작함.
"""

HEAD_DETAIL, HEAD_NOTE = "### 상세 설명", "### 유의사항"


def rules(cite, not_found):
    """cite: 근거 표시 예 ('[H0071]처럼 문서 ID'), not_found: 찾지 못했을 때 쓰는 문장"""
    return f"""형식 규칙 (마크다운으로 쓰며 화면에 그대로 그려집니다. 결론부터 쓰는 두괄식)
- 맨 앞에는 제목 없이, 질문에 대한 답(결론)을 1~2문장으로 짧게 씁니다. 건마다의 날짜·조문 나열은 상세 설명으로 보냅니다.
  근거 표시({cite})를 붙입니다. "핵심 답변"·"결론" 같은 제목은 쓰지 않습니다.
- 그다음 "{HEAD_DETAIL}" 제목 아래에 결론의 근거와 자세한 내용을 "- " 목록으로 씁니다. 항목마다 근거 표시를 붙이고,
  결론을 가르는 조건·수치·처리 상태 한 곳을 **굵게** 표시합니다. 결론 한두 문장으로 충분한 질문이면 이 제목은 쓰지 않습니다.
- "{HEAD_NOTE}": 안내·주의·확인할 점이 있을 때만 맨 끝에 "- " 목록으로 씁니다. 없으면 이 제목을 쓰지 않습니다. 근거에 없는 권고는 지어내지 않습니다.
- 제목은 "### "로 시작하고, 위 두 제목 말고 다른 제목과 번호 매기기는 쓰지 않습니다. 표는 여러 값을 나란히 비교할 때만 씁니다.
- 찾지 못했다고 답할 때는 제목 없이 "{not_found}"라는 문장만 씁니다."""


def add_note(text, line):
    """유의사항에 고정 안내 한 줄 붙이기 (코드가 넣는 문구, 예: 비조치의견서 '최종 판단은 준법감시부서 확인'). 없으면 제목째 붙임"""
    text = (text or "").rstrip()
    if HEAD_NOTE in text:
        return f"{text}\n- {line}"
    return f"{text}\n\n{HEAD_NOTE}\n- {line}"
